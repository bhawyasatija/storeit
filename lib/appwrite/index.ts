import "server-only";

import { Account, Avatars, Client, Storage, TablesDB } from "node-appwrite";
import { appwriteConfig, SESSION_COOKIE } from "@/lib/appwrite/config";
import { cookies } from "next/headers";

// Note: this module must NOT be marked "use server". Its exports return SDK
// clients (one of them holding the API key) and must never be exposed as
// callable server actions.

export const createSessionClient = async () => {
  const client = new Client()
    .setEndpoint(appwriteConfig.endpointUrl)
    .setProject(appwriteConfig.projectId);

  const session = (await cookies()).get(SESSION_COOKIE);

  if (!session || !session.value) throw new Error("No session");

  client.setSession(session.value);

  return {
    get account() {
      return new Account(client);
    },
    get tablesDB() {
      return new TablesDB(client);
    },
  };
};

export const createAdminClient = async () => {
  const client = new Client()
    .setEndpoint(appwriteConfig.endpointUrl)
    .setProject(appwriteConfig.projectId)
    .setKey(appwriteConfig.secretKey);

  return {
    get account() {
      return new Account(client);
    },
    get tablesDB() {
      return new TablesDB(client);
    },
    get storage() {
      return new Storage(client);
    },
    get avatars() {
      return new Avatars(client);
    },
  };
};
